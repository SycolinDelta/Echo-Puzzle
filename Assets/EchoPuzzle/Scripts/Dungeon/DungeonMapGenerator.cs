        /// <summary>
        /// 生成一个随机布局。
        ///
        /// ══════════════════════════════════════════════════════════════
        /// 生成顺序（需求："先随机确定好 Y 的位置，然后再随机确定其它房间"）
        ///
        ///   ① **先随机确定 Y** —— 从 4×4 的 16 格里等概率抽一格
        ///      （每格概率都是 1/16，Y 出现在任何位置的机会都相等）
        ///
        ///   ② **再随机确定 Z** —— 从剩下 15 格里抽，要求不与 Y 相邻
        ///      （曼哈顿距离 &gt; 1）
        ///
        ///   ③ **再随机填 2 个 A** —— 从剩下 14 格里抽 2 个，
        ///      要求整片 4 格连通
        ///
        ///   ★★ 不限制 Y/Z 的相邻块数量 ★★
        ///      它们可以和多个块相邻 —— 只是门里**只有一个**会被设为 1，
        ///      其余相邻的门一律设成 2（就是"门是关着的"）。
        ///
        ///   ★ 也允许 A 只有部分门打开，允许死胡同，允许多条路径。
        /// ══════════════════════════════════════════════════════════════
        /// </summary>
        private static Dictionary<Vector2Int, string> RandomLayout(System.Random rng)
        {
            // 全部 16 个格子
            var all = new List<Vector2Int>(GridRows * GridCols);
            for (int r = 0; r < GridRows; r++)
                for (int c = 0; c < GridCols; c++)
                    all.Add(new Vector2Int(r, c));

            // ★★ 为了让 Y 的 16 个位置**真正等概率**，
            //    先把 16 个位置全部打乱，按顺序逐个尝试作为 Y。
            //    每个 Y 位置尝试完所有组合才换下一个 —— 这样不会出现
            //    "中心位置更容易凑出连通组合" 导致的分布偏斜。
            Shuffle(all, rng);

            foreach (Vector2Int posY in all)
            {
                // ────────────────────────────────────────────────────
                // ② 再随机确定 Z：从剩下 15 格里挑，且不能和 Y 相邻
                // ────────────────────────────────────────────────────
                var zCands = new List<Vector2Int>(15);
                for (int i = 0; i < all.Count; i++)
                {
                    Vector2Int p = all[i];
                    if (p == posY) continue;

                    int dist = Mathf.Abs(p.x - posY.x) + Mathf.Abs(p.y - posY.y);
                    if (dist <= 1) continue;          // ★ 不能相邻

                    zCands.Add(p);
                }

                if (zCands.Count == 0) continue;      // 理论上不会（Y 至少 9 个非邻居）

                Shuffle(zCands, rng);

                foreach (Vector2Int posZ in zCands)
                {
                    // ────────────────────────────────────────────────
                    // ③ 再随机填 2 个 A：从剩下 14 格里挑 2 个，要求 4 格连通
                    // ────────────────────────────────────────────────
                    var aCands = new List<Vector2Int>(14);
                    for (int i = 0; i < all.Count; i++)
                    {
                        Vector2Int p = all[i];
                        if (p == posY || p == posZ) continue;
                        aCands.Add(p);
                    }

                    Shuffle(aCands, rng);

                    // 穷举 aCands 里的所有 C(n,2) 组合（n = 14 -> 91 种）
                    for (int i0 = 0; i0 < aCands.Count; i0++)
                    {
                        for (int i1 = i0 + 1; i1 < aCands.Count; i1++)
                        {
                            var set = new HashSet<Vector2Int>
                            {
                                posY, posZ, aCands[i0], aCands[i1]
                            };

                            if (!IsConnected(set)) continue;

                            return new Dictionary<Vector2Int, string>
                            {
                                { posY,       "Y" },
                                { posZ,       "Z" },
                                { aCands[i0], "A" },
                                { aCands[i1], "A" },
                            };
                        }
                    }
                }
            }

            return null;
        }

        /// <summary>Fisher-Yates 洗牌（就地打乱）。</summary>
        private static void Shuffle<T>(List<T> list, System.Random rng)
        {
            for (int i = list.Count - 1; i > 0; i--)
            {
                int j = rng.Next(i + 1);
                T t = list[i]; list[i] = list[j]; list[j] = t;
            }
        }

        /// <summary>
        /// 取一个随机数发生器。
        ///
        /// ── 为什么不用自增 LCG 种子 ──────────────────────────
        ///   之前用的是：
        ///       s_Seed = (s_Seed * 1103515245 + 12345) & 0x7FFFFFFF;
        ///       return new System.Random(s_Seed);
        ///
        ///   问题有两个：
        ///     1. LCG 的**低位质量极差**，相邻种子的低位几乎一样。
        ///       而 RandomLayout 用 rng.Next(16) / rng.Next(4) 选格子 ——
        ///       Next(2^k) 正是直接取低位，于是相邻几次重建会拿到
        ///       几乎相同的 picks，表现为"出口方向成批旋转"。
        ///     2. System.Random(int) 的内部初始化对相近种子很敏感度低，
        ///       相邻种子会产出相似的序列。
        ///
        ///   现在改成：
        ///     · 用 Guid.NewGuid() 取真正的随机源（操作系统熵）
        ///     · 再叠加一路自增计数做混淆，保证即使同一帧内连续调用也一定不同
        /// </summary>
        private static System.Random NextRng()
        {
            unchecked
            {
                // ① 真随机源（OS 熵）
                byte[] bytes = System.Guid.NewGuid().ToByteArray();
                int entropy = System.BitConverter.ToInt32(bytes, 0);

                // ② 自增计数（保证连续调用一定不同）
                s_Seed++;

                // ③ 充分混淆：把熵和计数混合，避免低位相关
                uint h = (uint)entropy ^ (uint)(s_Seed * 2654435761u);
                h ^= h >> 16;
                h *= 0x7feb352du;
                h ^= h >> 15;
                h *= 0x846ca68bu;
                h ^= h >> 16;

                s_Seed = (int)(h & 0x7FFFFFFF);

                return new System.Random(s_Seed);
            }
        }

        /// <summary>自增计数（每次重建都推进，保证连续调用拿到的种子不同）。</summary>
        private static int s_Seed = System.Environment.TickCount;

        /// <summary>这组格子是不是 4-邻接连成一片。</summary>
        private static bool IsConnected(HashSet<Vector2Int> set)
        {
            if (set.Count == 0) return false;

            var start = default(Vector2Int);
            foreach (Vector2Int p in set) { start = p; break; }

            var seen = new HashSet<Vector2Int> { start };
            var q    = new Queue<Vector2Int>();
            q.Enqueue(start);

            while (q.Count > 0)
            {
                Vector2Int p = q.Dequeue();

                for (int d = 0; d < 4; d++)
                {
                    var n = new Vector2Int(p.x + DirVec[d].x, p.y + DirVec[d].y);
                    if (!set.Contains(n)) continue;
                    if (!seen.Add(n)) continue;
                    q.Enqueue(n);
                }
            }

            return seen.Count == set.Count;
        }

        /// <summary>某个块的邻居方向（只算分块矩阵里真的有块的）。</summary>
        private static List<int> AvailDirs(Vector2Int p, Dictionary<Vector2Int, string> lay)
        {
            var list = new List<int>(4);
            for (int d = 0; d < 4; d++)
            {
                var n = new Vector2Int(p.x + DirVec[d].x, p.y + DirVec[d].y);
                if (lay.ContainsKey(n)) list.Add(d);
            }
            return list;
        }

        /// <summary>两个相邻块之间的"连接"（成对的门）。</summary>
        private struct Link
        {
            public Vector2Int a;   public int da;
            public Vector2Int b;   public int db;
        }

        private static List<Link> BuildLinks(Dictionary<Vector2Int, string> lay)
        {
            var list = new List<Link>();
            var seen = new HashSet<string>();

            foreach (var kv in lay)
            {
                Vector2Int p = kv.Key;

                for (int d = 0; d < 4; d++)
                {
                    var q = new Vector2Int(p.x + DirVec[d].x, p.y + DirVec[d].y);
                    if (!lay.ContainsKey(q)) continue;

                    int od = Opposite(d);

                    // 去重（无向边）
                    string key = p.x + "," + p.y + "," + d;
                    string rkey = q.x + "," + q.y + "," + od;
                    if (key.CompareTo(rkey) > 0) key = rkey;
                    if (!seen.Add(key)) continue;

                    list.Add(new Link { a = p, da = d, b = q, db = od });
                }
            }

            return list;
        }

        /// <summary>
        /// 求解门的状态：返回 {(块, 方向) -> 0/1}，0 = 设成 2，1 = 设成 1。
        ///
        /// ★ 会**枚举所有**满足"Y/Z 恰好 1 门、A 至少 1 门"的分配，
        ///   然后逐个试，直到某一个能让玩家从 Y 走到 Z。
        /// </summary>
        private static Dictionary<(int, int, int), int> SolveGates(
            Dictionary<Vector2Int, string> lay,
            Dictionary<Vector2Int, int[,]> grids,
            System.Random rng)
        {
            var av = new Dictionary<Vector2Int, List<int>>();
            foreach (var kv in lay) av[kv.Key] = AvailDirs(kv.Key, lay);

            foreach (var kv in lay)
                if (av[kv.Key].Count == 0) return null;

            List<Link> links = BuildLinks(lay);
            int n = links.Count;

            // 收集所有满足门约束的分配
            var cands = new List<Dictionary<(int, int, int), int>>();

            int total = 1 << n;

            for (int mask = 0; mask < total; mask++)
            {
                var st = new Dictionary<(int, int, int), int>();

                for (int i = 0; i < n; i++)
                {
                    int v = (mask >> i) & 1;
                    Link L = links[i];

                    st[(L.a.x, L.a.y, L.da)] = v;
                    st[(L.b.x, L.b.y, L.db)] = v;
                }

                bool ok = true;

                foreach (var kv in lay)
                {
                    Vector2Int p = kv.Key;
                    string mark = kv.Value;

                    int cnt = 0;
                    foreach (int d in av[p]) cnt += st.TryGetValue((p.x, p.y, d), out int vv) ? vv : 0;

                    if (mark == "Y" || mark == "Z")
                    {
                        if (cnt != 1) { ok = false; break; }     // 只能有 1 个 1 门
                    }
                    else
                    {
                        if (cnt < 1) { ok = false; break; }      // 至少 1 个
                    }
                }

                if (ok) cands.Add(st);
            }

            if (cands.Count == 0) return null;

            // 打乱后逐个试连通性
            for (int i = cands.Count - 1; i > 0; i--)
            {
                int j = rng.Next(i + 1);
                var t = cands[i]; cands[i] = cands[j]; cands[j] = t;
            }

            foreach (var st in cands)
                if (ConnectivityOk(lay, grids, st, av)) return st;

            return null;
        }

        /// <summary>
        /// 【地牢模式】"已开启的出口门"标记表。
        ///
        /// ★ 模板里的 4 = 出口门；生成时按规则改写成 1（开）或 2（关）。
        ///
        ///   需求："在4变成1时给这个单元格打一个与其他任何系统都毫无关联的标记，
        ///         在怪物潮结束的时候带有这个标记的单元格会释放一次声波。"
        ///
        ///   ★ 所以矩阵里的**数字完全不改**（开着的门仍然是 1），
        ///     只是在旁边单独记一份"哪些格子是开着的门"。
        ///     这份表和建图 / 连通 / 怪物区 / 封锁 都没有任何关系。
        ///
        /// ★ key = 大矩阵坐标 (x, z)
        /// ★ 只在**含怪物区的块**里打标记（其它块的门不记）
        /// </summary>
        private static readonly HashSet<Vector2Int> s_OpenGateMarks
            = new HashSet<Vector2Int>();

        /// <summary>
        /// 【给 MonsterZone 用】返回当前地图里所有**带标记的出口门格子**（大矩阵坐标）。
        ///
        /// ★ 标记是在 ApplyGates 里打的：模板里的 4 被写成 1（开着）时，
        ///   如果这一块含怪物区，就把这个坐标记进 <see cref="s_OpenGateMarks"/>。
        ///
        /// ★ 这份标记和建图 / 连通判定 / 怪物区 / 封锁**没有任何关系** ——
        ///   矩阵里的数字完全没变（开着的门仍然是 1）。
        /// </summary>
        public static List<Vector2Int> FindOpenGateCells()
        {
            BuildSlots();

            return new List<Vector2Int>(s_OpenGateMarks);
        }

        /// <summary>
        /// 把门的 1/2 结果写进每块的矩阵副本。
        /// </summary>
        /// <param name="originalTemplates">
        /// 每块**原始模板**（未改写过的矩阵）。门的位置从它算。
        ///
        /// ★ 为什么必须传它：
        ///   grids 里的矩阵是"工作副本"，SolveGates 为了试各种候选分配
        ///   会反复调用 ApplyGates 把里面的 4 改写成 1/2。
        ///   等到 BuildSlots 想记录标记时再去 grids 里找 4 —— 早就没有了。
        ///
        ///   所以门的位置一律从**原始模板**算。
        ///   （传 null 时退化成用 grids，只为兼容旧调用。）
        /// </param>
        /// <param name="recordMarks">
        /// 是否顺便记录"开着的出口门"标记。
        ///
        /// ★ 只有**最终确定**的那次调用才传 true。
        ///   ConnectivityOk 会为了试各种候选分配反复调用 ApplyGates，
        ///   那些中间态不能污染标记表。
        /// </param>
        private static void ApplyGates(
            Dictionary<Vector2Int, string> lay,
            Dictionary<Vector2Int, int[,]> grids,
            Dictionary<(int, int, int), int> st,
            Dictionary<Vector2Int, List<int>> av,
            Dictionary<Vector2Int, int[,]> originalTemplates = null,
            bool recordMarks = false)
        {
            if (recordMarks) s_OpenGateMarks.Clear();

            foreach (var kv in lay)
            {
                Vector2Int p = kv.Key;

                int[,] mat = grids[p];

                // ★ 门的位置从**原始模板**算（模板里 4 还在原位），
                //   没有原始模板时退回用工作副本。
                int[,] src = null;

                if (originalTemplates != null)
                    originalTemplates.TryGetValue(p, out src);

                if (src == null) src = mat;

                GateInfo gi = GetGates(src);

                // 这一块里有没有怪物区（值 3）—— 有才给门打标记
                bool hasMonsterZone = ContainsMonsterZone(src);

                foreach (var gk in gi.Gates)
                {
                    int d = gk.Key;

                    int val;
                    if (av[p].Contains(d))
                    {
                        // 对侧有块：按求解结果（默认 0 -> 设成 2）
                        st.TryGetValue((p.x, p.y, d), out int v);
                        val = v == 1 ? 1 : 2;
                    }
                    else
                    {
                        // 对侧是空块：一律 2
                        val = 2;
                    }

                    foreach (Vector2Int cell in gk.Value)
                    {
                        // ★ 矩阵里照常写 1 / 2，**不掺任何特殊数字**
                        mat[cell.x, cell.y] = val;

                        // ★★ 4 -> 1（开着的门）+ 这块含怪物区 -> 打标记 ★★
                        //
                        //   ★ 只往 s_OpenGateMarks 里记一笔，矩阵数字不变。
                        //     这份标记和建图 / 连通 / 怪物区 / 封锁 没有任何关系。
                        if (recordMarks && val == 1 && hasMonsterZone)
                        {
                            int gx = p.x * ModuleSize + cell.x;
                            int gz = p.y * ModuleSize + cell.y;

                            s_OpenGateMarks.Add(new Vector2Int(gx, gz));
                        }
                    }
                }
            }
        }

        /// <summary>这块模板里有没有怪物区（值 3）。</summary>
        private static bool ContainsMonsterZone(int[,] mat)
        {
            if (mat == null) return false;

            for (int x = 0; x < ModuleSize; x++)
                for (int z = 0; z < ModuleSize; z++)
                    if (mat[x, z] == 3) return true;

            return false;
        }

        /// <summary>从 8 出发能不能走到 9（走 1 / 3 / 8 / 9）。</summary>
        private static bool ConnectivityOk(
            Dictionary<Vector2Int, string> lay,
            Dictionary<Vector2Int, int[,]> grids,
            Dictionary<(int, int, int), int> st,
            Dictionary<Vector2Int, List<int>> av)
        {
            ApplyGates(lay, grids, st, av);

            return Reachable(lay, grids);
        }

        /// <summary>
        /// 四元组（块行, 块列, 模块内 X, 模块内 Z）—— BFS 的 visited 键。
        /// </summary>
        private struct Vector4Int : System.IEquatable<Vector4Int>
        {
            public int a, b, c, d;

            public Vector4Int(int a, int b, int c, int d)
            {
                this.a = a; this.b = b; this.c = c; this.d = d;
            }

            public bool Equals(Vector4Int o) =>
                a == o.a && b == o.b && c == o.c && d == o.d;

            public override bool Equals(object obj) =>
                obj is Vector4Int o && Equals(o);

            public override int GetHashCode() =>
                ((a * 397) ^ b) * 397 ^ ((c * 397) ^ d);
        }

        /// <summary>
        /// 在大地图上做一次 BFS：起点 = 8，终点 = 9。
        ///
        /// ★ 直接按块查矩阵，不拼 140×140（省内存也更快）。
        /// </summary>
        private static bool Reachable(
            Dictionary<Vector2Int, string> lay,
            Dictionary<Vector2Int, int[,]> grids)
        {
            Vector2Int startBlock = default;
            int startX = 0, startZ = 0;
            bool foundStart = false;

            Vector2Int goalBlock = default;
            bool foundGoal = false;

            // 找 8 和 9 的位置
            foreach (var kv in lay)
            {
                Vector2Int p = kv.Key;
                int[,] m = grids[p];

                for (int x = 0; x < ModuleSize; x++)
                {
                    for (int z = 0; z < ModuleSize; z++)
                    {
                        int v = m[x, z];

                        if (v == 8) { startBlock = p; startX = x; startZ = z; foundStart = true; }
                        else if (v == 9) { goalBlock = p; foundGoal = true; }
                    }
                }
            }

            if (!foundStart || !foundGoal) return false;

            // BFS（用小范围的 visited 集合）
            var visited = new HashSet<Vector4Int>();
            var q = new Queue<Vector4Int>();

            q.Enqueue(new Vector4Int(startBlock.x, startBlock.y, startX, startZ));
            visited.Add(new Vector4Int(startBlock.x, startBlock.y, startX, startZ));

            while (q.Count > 0)
            {
                Vector4Int cur = q.Dequeue();

                var blk = new Vector2Int(cur.a, cur.b);
                int v = grids[blk][cur.c, cur.d];
                if (v == 9) return true;

                for (int d = 0; d < 4; d++)
                {
                    int nx = cur.c + DirVec[d].x;
                    int nz = cur.d + DirVec[d].y;

                    var nblk = blk;

                    // 跨块
                    if (nx < 0 || nx >= ModuleSize || nz < 0 || nz >= ModuleSize)
                    {
                        nblk = new Vector2Int(blk.x + DirVec[d].x,
                                              blk.y + DirVec[d].y);
                        if (!lay.ContainsKey(nblk)) continue;
                    }

                    nx = ((nx % ModuleSize) + ModuleSize) % ModuleSize;
                    nz = ((nz % ModuleSize) + ModuleSize) % ModuleSize;

                    int nv = grids[nblk][nx, nz];
                    if (nv != 1 && nv != 3 && nv != 8 && nv != 9) continue;

                    var key = new Vector4Int(nblk.x, nblk.y, nx, nz);
                    if (!visited.Add(key)) continue;

                    q.Enqueue(key);
                }
            }

            return false;
        }

        /// <summary>
        /// 建立分块矩阵的布局（随机地图）。
        ///
        /// ★ 会不断重试，直到找到"能连通"的布局 + 门分配。
        /// </summary>
        private static void BuildSlots()
        {
            if (s_SlotsBuilt) return;
            s_SlotsBuilt = true;

            // 全部清空
            for (int r = 0; r < GridRows; r++)
                for (int c = 0; c < GridCols; c++)
                    s_Slots[r, c] = null;

            if (s_Layout == null) s_Layout = new Dictionary<Vector2Int, string>();
            s_Layout.Clear();

            // ★ 用**共享**的随机数发生器 + 每次递增种子
            //
            //   new System.Random() 在同一帧内创建多次会拿到**相同种子**
            //   （.NET 用 Environment.TickCount），导致每次重建地图都一模一样。
            //   这里用一个静态实例 + 递增种子，保证每次重建都不同。
            var rng = NextRng();

            for (int attempt = 0; attempt < 200; attempt++)
            {
                Dictionary<Vector2Int, string> lay = RandomLayout(rng);
                if (lay == null) { s_FailLayout++; continue; }

                // 每块**独立随机**抽一个模板，并复制一份
                // （门的 1/2 要写进副本，不能改原模板）
                //
                // ★★ 这就是"一个字母对应多个模板"的落地 ★★
                //   同一张地图里的两个 A 块各自调一次 GetTemplate("A", rng)，
                //   可能抽到同一个模板（AA），也可能抽到不同的（AA / AC）。
                var grids = new Dictionary<Vector2Int, int[,]>();

                // ★ 同时记一份**原始模板**：SolveGates 会把 grids 里的 4
                //   改写成 1/2，之后再想找门的位置就只能靠它了。
                var origTemplates = new Dictionary<Vector2Int, int[,]>();

                bool anyNull = false;

                foreach (var kv in lay)
                {
                    int[,] src = GetTemplate(kv.Value, rng);

                    if (src == null)
                    {
                        // 字母没注册 / 池子是空的 —— 这个布局作废，换一个
                        anyNull = true;
                        break;
                    }

                    origTemplates[kv.Key] = src;

                    var copy = new int[ModuleSize, ModuleSize];

                    // 显式双循环复制（不用 Array.Copy，避免多维数组展平的歧义）
                    for (int x = 0; x < ModuleSize; x++)
                        for (int z = 0; z < ModuleSize; z++)
                            copy[x, z] = src[x, z];

                    grids[kv.Key] = copy;
                }

                if (anyNull) { s_FailLayout++; continue; }

                var st = SolveGates(lay, grids, rng);

                if (st == null)
                {
                    s_FailSolve++;
                    continue;
                }

                // 成功：写回 s_Slots
                foreach (var kv in lay)
                {
                    s_Slots[kv.Key.x, kv.Key.y] = grids[kv.Key];
                    s_Layout[kv.Key] = kv.Value;
                }

                // ★★ 记录"开着的出口门"标记 ★★
                //
                //   SolveGates 内部为了试各种候选分配反复调用过 ApplyGates，
                //   那些中间态不能算数。这里用**最终确定的**门状态再跑一遍
                //   ApplyGates，并打开 recordMarks，把标记表填好。
                var av2 = new Dictionary<Vector2Int, List<int>>();
                foreach (var kv in lay) av2[kv.Key] = AvailDirs(kv.Key, lay);

                // ★ 传入原始模板 —— grids 里的 4 早已被 SolveGates 改成 1/2 了
                ApplyGates(lay, grids, st, av2, origTemplates, recordMarks: true);

                s_MapCache = null;

                return;
            }

            // ★ 兜底：200 次都失败时用一个**保证可连通**的固定布局
            //
            //   纵向一排 Y / A / A / Z，所有相邻门都设为 1。
            //   这样即使随机算法出问题，玩家也一定能玩。
            BuildFallbackLayout();
        }

        /// <summary>
        /// 兜底布局：纵向一排 Y / A / A / Z，所有相邻门全部设为 1。
        /// 一定能从 Y 走到 Z。
        /// </summary>
        private static void BuildFallbackLayout()
        {
            Debug.LogWarning("[地牢] 随机地图生成失败，改用固定的兜底布局（Y-A-A-Z 竖排）。");

            var lay = new Dictionary<Vector2Int, string>
            {
                { new Vector2Int(0, 1), "Y" },
                { new Vector2Int(1, 1), "A" },
                { new Vector2Int(2, 1), "A" },
                { new Vector2Int(3, 1), "Z" },
            };

            for (int r = 0; r < GridRows; r++)
                for (int c = 0; c < GridCols; c++)
                    s_Slots[r, c] = null;

            s_Layout.Clear();

            // 所有块之间的连接一律设成 1
            var st = new Dictionary<(int, int, int), int>
            {
                { (0, 1, 1), 1 },   // Y 下
                { (1, 1, 0), 1 },   // A1 上
                { (1, 1, 1), 1 },   // A1 下
                { (2, 1, 0), 1 },   // A2 上
                { (2, 1, 1), 1 },   // A2 下
                { (3, 1, 0), 1 },   // Z 上
            };

            var grids = new Dictionary<Vector2Int, int[,]>();


            // ★ 原始模板（ApplyGates 要用它找门的位置）
            var origTemplates = new Dictionary<Vector2Int, int[,]>();

            foreach (var kv in lay)
            {
                // 兜底布局用池里的**第一个**模板（不随机，保证可复现）
                int[,] srcm = GetTemplate(kv.Value);
                var copy = new int[ModuleSize, ModuleSize];
                for (int x = 0; x < ModuleSize; x++)
                    for (int z = 0; z < ModuleSize; z++)
                        copy[x, z] = srcm[x, z];
                grids[kv.Key] = copy;
                origTemplates[kv.Key] = srcm;

            }

            var av = new Dictionary<Vector2Int, List<int>>();
            foreach (var kv in lay) av[kv.Key] = AvailDirs(kv.Key, lay);

            // ★ 兜底布局也要记录"开着的出口门"标记
            ApplyGates(lay, grids, st, av, origTemplates, recordMarks: true);

            foreach (var kv in lay)
            {
                s_Slots[kv.Key.x, kv.Key.y] = grids[kv.Key];
                s_Layout[kv.Key] = kv.Value;
            }

            s_MapCache = null;
        }

