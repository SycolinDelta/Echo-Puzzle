        /// <summary>
        /// 开局时序：等玩家选完开局的 buff，再创建 / 加载第 1 层地图。
        ///
        /// ★ 和 <see cref="NextStageRoutine"/> 用同一个"等待标志"，
        ///   所以 DungeonBuffSelectUI 的启动逻辑（等 IsWaitingBuff）不用改。
        ///
        /// ── ⚠ 时序陷阱（曾经导致"首次进游戏手刀/武器不受鼠标控制、不出光带脚印"）──
        ///
        ///   GameUI.StartGameInternal() 的流程是：
        ///       WorldSnapshot.CaptureStart()
        ///       ① TeleportToDungeonSpawn()   ← 这里地图还没建！
        ///       ② QueueDungeonStarterBuff()
        ///       ③ EnterPlaying()
        ///
        ///   而开局地图现在要等玩家选完 buff 才建（就是本协程）。
        ///   所以 ① 执行时 m_HasSpawn 还是 false，
        ///   TeleportPlayerToSpawn() 直接 return —— **玩家没有被传送**，
        ///   还站在场景里的原始坐标上。
        ///
        ///   而 BuildStage() 建完图之后会自己 PlacePlayer(出生点)，
        ///   所以位置最终是对的；但"传送"这个动作从没发生过，
        ///   玩家的 CharacterController / 相机 / 朝向都没被初始化一次，
        ///   表现就是：手刀和武器不跟鼠标、不出光带和脚印。
        ///   点"重新开始"能好，是因为那时地图已经存在（m_HasSpawn=true），
        ///   ① 这次真的传送了。
        ///
        ///   ✔ 修法：本协程建成地图后再显式传送 + 复位一次，
        ///     让"首次进入"和"重新开始"走完全一样的初始化路径。
        /// </summary>
        private IEnumerator StarterStageRoutine()
        {
            // ① ★ 先把屏幕变全黑，并且清掉任何残留的地图物体 ★
            //
            //   需求："我要的是先跳出选buff界面，然后才显示地图。"
            //
            //   ★ 之前 m_FadeAlpha 初始就是 0（全黑），但这里**没有任何建图**，
            //     所以理论上应该看不到东西。真正让"地图先出现"的，
            //     是 GameUI.EnterPlaying() -> SetWorldVisible(true) 之后
            //     相机开始渲染场景 —— 而场景里可能还留着上一次
            //     （例如从暂停菜单重新开始、或编辑器里第二次 Play）
            //     没清干净的地图。
            //
            //   这里显式把黑幕拉到不透明 + 清一次残骸，保证"选卡时一定看不到地图"。
            m_FadeIn    = false;
            m_FadeAlpha = 1f;
            m_Fading    = false;

            ClearStage();

            // ② 告诉 UI："我在等 buff" —— UI 看到它就会弹开局三选一
            m_WaitingBuff = true;

            // ③ ★ 等 buff 界面真正打开，然后**立刻**建图 + 传送 ★
            //
            //   需求（用户给的时序）：
            //     "1、玩家点击新游戏，跳出buff界面。
            //      2、跳出buff界面后，立即新建地图，然后将玩家物体传送至出生点，
            //        但是此时不要显示地图和玩家物体，不要让玩家操控玩家物体。
            //      3、玩家选好buff后，退出buff界面，并显示地图和玩家物体。
            //      4、玩家正常游玩。"
            //
            //   ★ 所以这里不能等玩家选完再建图 —— 而是**界面一出来就建**。
            //     建好后世界保持隐藏（黑幕 + GameUI.SetWorldVisible(false)），
            //     等 Close -> NotifyBuffSelected 清了 m_WaitingBuff 才显示。
            //   ★ 加超时保护：万一因为某种原因界面没弹出来，
            //     也不能让地图永远不建（会卡死在黑屏）。
            float waitDeadline = Time.unscaledTime + StarterBuffUiTimeout;

            while (!BuffUiOpen() && m_WaitingBuff &&
                   Time.unscaledTime < waitDeadline)
            {
                yield return null;
            }

            // ④ 建图（RebuildStage 内部 BuildStage 会把玩家摆到格子 8）
            RebuildStage();

            // ⑤ 再走一次正式传送接口（和「重新开始」同一条路径）
            TeleportPlayerToSpawn();

            // ⑥ 等两帧让 CharacterController / 相机稳定
            yield return null;
            yield return null;

            // ⑦ 等玩家选完 buff（Close -> NotifyBuffSelected 把标志清掉）
            while (m_WaitingBuff) yield return null;

            // ⑧ 选完才淡入 = 显示地图和玩家
            m_FadeIn = true;
            m_Fading = true;

            while (m_Fading) yield return null;
        }

        /// <summary>buff 三选一界面当前是否开着。</summary>
        private static bool BuffUiOpen()
        {
            var ui = DungeonBuffSelectUI.Instance;
            return ui != null && ui.IsOpen;
        }

        /// <summary>
        /// 开局等 buff 界面弹出的最长等待（秒）。
        /// 超时就直接建图，避免因为界面异常而永远黑屏。
        /// </summary>
        private const float StarterBuffUiTimeout = 5f;

        private void Update()
        {
            // ---- 调试：F7 切换「出生房必定带商店」并立刻重建（测商店用）----
            //
            // ★ 为什么用快捷键而不是只能勾 Inspector：
            //   这个组件是运行时由 EchoRuntimeBootstrap 创建的，
            //   编辑模式下 Hierarchy 里根本没有它，只能进 Play 之后再找。
            if (Input.GetKeyDown(KeyCode.F7))
            {
                DebugForceShopRoom  = !DebugForceShopRoom;
                debugForceShopRoom  = DebugForceShopRoom;

                Debug.Log($"[调试] 出生房必定带商店 = {DebugForceShopRoom}，正在重建地图…");

                RestartDungeonMap();
            }

            // 淡入淡出的推进
            if (!m_Fading) return;

            float dt = Time.unscaledDeltaTime;
            float speed = fadeDuration > 0.0001f ? 1f / fadeDuration : 999f;

            m_FadeAlpha = Mathf.MoveTowards(m_FadeAlpha, m_FadeIn ? 0f : 1f, speed * dt);

            if (m_FadeIn && m_FadeAlpha <= 0f)
            {
                m_FadeAlpha = 0f;
                m_Fading    = false;
            }
            else if (!m_FadeIn && m_FadeAlpha >= 1f)
            {
                m_FadeAlpha = 1f;
                m_Fading    = false;
            }
        }

        // ------------------------------------------------------------------ 切层

        /// <summary>玩家进入 NextStage：淡出 -> 重建 -> 淡入。</summary>
        private void HandleNextStage()
        {
            if (m_Transitioning) return;

            StartCoroutine(NextStageRoutine());
        }

        private IEnumerator NextStageRoutine()
        {
            m_Transitioning = true;

            // ---- 1) 淡出到全黑 ----
            m_FadeIn  = false;
            m_Fading  = true;

            while (m_Fading) yield return null;

            // ---- 2) 清空场上残留（先清，免得旧光带拖到选 buff 期间）----
            ClearTransientEffects();

            // ---- 3) ★ 先弹 buff 选择，等玩家选完再建新地图 ★ ----
            //
            // 需求："在进入下一层选buff时，下一层的地图应当在选完buff后才出现。"
            //
            //   ★ 顺序改成：淡出全黑 -> 选 buff -> 建地图 -> 淡入
            //     之前是：淡出 -> 建地图 -> 淡入 -> 选 buff
            //     那时玩家能在选 buff 前看到新地图的轮廓，不符合要求。
            //
            //   ★ 整个过程屏幕是全黑的（m_FadeAlpha 保持 1），
            //     所以"选 buff 时看不到地图"是自然结果。
            m_WaitingBuff = true;

            while (m_WaitingBuff) yield return null;

            // ---- 4) 玩家选完 buff -> 现在才重建下一层 ----
            RebuildStage();

            // ---- 5) 淡入 ----
            m_FadeIn = true;
            m_Fading = true;

            while (m_Fading) yield return null;

            m_Transitioning = false;
        }

        /// <summary>
        /// 下一层是否正在等待玩家选 buff。
        /// </summary>
        public bool IsWaitingBuff => m_WaitingBuff;

        /// <summary>
        /// 【给 DungeonBuffSelectUI 调】告诉地图"buff 已经选完了，可以建下一层了"。
        ///
        /// ★ 幂等：没在等待时调用什么也不做。
        /// </summary>
        public void NotifyBuffSelected()
        {
            m_WaitingBuff = false;
        }

        /// <summary>是否正在等待玩家选 buff（换层流程内部用）。</summary>
        private bool m_WaitingBuff;

        /// <summary>
        /// 清掉上一张地图遗留在场上的东西：光带、标记、脚印。
        ///
        /// ★ 换地图时这些必须一起消失 —— 否则上一层的声波残留会留在
        ///   新地图里，玩家会以为那是新地图的轮廓。
        ///
        /// ★ 也清掉正在飞的石子 / 匕首的残留，避免跨层残留。
        /// </summary>
        private void ClearTransientEffects()
        {
            // ---- 光带 ----
            SonarSystem sonar = FindObjectOfType<SonarSystem>();
            if (sonar != null)
            {
                var trail = sonar.GetComponentInChildren<SonarTrailRenderer>(true);
                if (trail != null) trail.ClearTrails();
            }

            // ---- 标记 ----
            MarkerSystem markers = FindObjectOfType<MarkerSystem>(true);
            if (markers != null) markers.ClearMarkers();

            // ---- 脚印 ----
            FootprintSystem prints = FindObjectOfType<FootprintSystem>(true);
            if (prints != null) prints.ClearFootprints();

            // ---- 石子（地牢模式里没有，但保险起见也清一下）----
            StoneThrowSystem stones = FindObjectOfType<StoneThrowSystem>(true);
            if (stones != null) stones.ClearStones();
        }

        /// <summary>
        /// 清掉旧地图并**重新随机**生成一层。
        ///
        /// ★★ 三个调用时机（需求）★★
        ///     1. 开始新游戏   -> Start() 里调一次
        ///     2. 进入下一层   -> NextStageRoutine() 里调
        ///     3. 点"重新开始" -> GameUI.RestartGame -> ResetDungeonSystems -> RestartDungeonMap()
        ///
        /// ★ 每次都**重新随机**布局：先 RerollLayout() 清掉缓存，
        ///   BuildStage -> GetCell -> SlotAt -> BuildSlots 就会重新抽一次。
        /// </summary>
        public void RebuildStage()
        {
            RebuildStage(advanceStage: true);
        }

        /// <summary>
        /// 重建地图。
        /// </summary>
        /// <param name="advanceStage">
        /// true  = 层数 +1（进入下一层）
        /// false = 层数不变（重新开始同一层，但地图重新随机）
        /// </param>
        public void RebuildStage(bool advanceStage)
        {
            // ★ 调试开关：让"出生房"必定带商店（勾上 Inspector 里的 Debug Force Shop Room 后重开一局）
            DebugForceShopRoom = debugForceShopRoom;

            if (advanceStage) CurrentStage++;
            else              CurrentStage = 1;      // 重新开始 = 回到第 1 层

            // ★★ 每次重建都重新随机布局 ★★
            //
            //   不调这句的话，s_SlotsBuilt 一直是 true，
            //   BuildSlots() 会直接 return，地图永远长一样。
            RerollLayout();

            // ★★ 层数缩放：每过一层，怪物血量 / 击杀回蓝 ×1.25 ★★
            //
            //   CurrentStage 从 0 起步，第一次 RebuildStage 后变成 1 -> 第 1 层 = ×1.0。
            //   把层号交给 DungeonBuffState，它内部算 StageScale = 1.25^(n-1)。
            //
            //   ★ 调用的是**静态**方法：不依赖 Instance 是否已创建，
            //     避免 Bootstrap 与 MapGenerator 的初始化时序问题。
            DungeonBuffState.SetStage(CurrentStage);

            ClearStage();
            BuildStage();

            // ★★ 新地图建好了 -> 解锁全场触发区 ★★
            //
            //   上一层的 NextStage 触发时调了 TriggerVolume.LockAll()，
            //   这里必须解锁，否则新一层的触发区全都按不动。
            TriggerVolume.UnlockAll();

            // ★★ 刷新玩家技能 CD ★★
            //
            //   需求："玩家的技能应当刷新cd。"
            if (m_Player == null) m_Player = FindObjectOfType<PlayerController>();
            if (m_Player != null) m_Player.ResetDungeonCooldowns();

            // ★ 淡入不再由这里决定 —— 交给调用方 ★
            //
            //   · 开局（StarterStageRoutine）：保持黑幕，由协程自己淡入
            //   · 下一层（NextStageRoutine）：同样是协程自己淡入
            //   · 重新开始（RestartDungeonMap）：见下面，立刻全亮
            //
            //   以前这里无条件 m_FadeAlpha = 0f，
            //   导致开局选完 buff 的瞬间画面是**硬切**进来的（没有淡入）。
        }

        /// <summary>
        /// 【重新开始】回到第 1 层，并**重新随机**生成地图。
        ///
        /// ★ 给 GameUI.RestartGame 调用。
        /// ★ 和"进入下一层"的区别：层数重置回 1（难度缩放也回到 ×1.0）。
        /// </summary>
        public void RestartDungeonMap()
        {
            // 先清掉怪物潮 / 怪物区里的残留（它们依赖上一层的格子）
            var waves = FindObjectOfType<MonsterWaveManager>();
            if (waves != null) waves.ForceClear();

            var zone = MonsterZone.Instance;
            if (zone != null) zone.ResetProgress();

            RebuildStage(advanceStage: false);

            // 回到出生点
            TeleportPlayerToSpawn();

            // ★ 重新开始：立刻全亮（原来这句在 RebuildStage 里，现在搬到这里）★
            //
            //   重新开始没有"黑幕 -> 淡入"的过程，玩家点完按钮就该看到画面。
            m_FadeAlpha = 0f;
            m_FadeIn    = true;
            m_Fading    = true;
        }

        /// <summary>清空上一层的所有生成物。</summary>
        private void ClearStage()
        {
            m_NextStageVolumes.Clear();

            // ★ 商店的"玩家在区域内"计数是静态的，换层 / 重开时必须清零，
            //   否则上一层的残留会让新一层的商店永远打不开。
            DungeonShopZone.ResetForNewMap();

            if (m_Root == null) return;

            for (int i = m_Root.childCount - 1; i >= 0; i--)
            {
                Destroy(m_Root.GetChild(i).gameObject);
            }
        }

        // ------------------------------------------------------------------ 建图

        /// <summary>按 <see cref="MapMatrix"/> 生成整张地图。</summary>
        private void BuildStage()
        {
            Vector3 playerSpawn = Vector3.zero;
            bool    hasSpawn    = false;

            // ★ 数字 3 的格子（怪物区地板），建完后交给 MonsterZone
            var monsterCells = new List<Vector2Int>();

            // ---- 地板 / 墙 / 出生点 / 下一层 ----
            //
            // ★ 用 GetCell 而不是 MapMatrix[x, z] ——
            //   GetCell 直接按 (x, z) 算出落在哪个模块，省掉一次 105×35 的拼装复制。
            for (int x = 0; x < RowsX; x++)
            {
                for (int z = 0; z < ColsZ; z++)
                {
                    int v = GetCell(x, z);

                    switch (v)
                    {
                        case 1:   // 地板：上下各一块
                            SpawnCube(x, floorBottomY, z, floorMaterial);
                            SpawnCube(x, floorTopY,    z, floorMaterial);
                            break;

                        case 2:   // 墙：从下到上一整排
                            for (int y = wallBottomY; y <= wallTopY; y++)
                                SpawnCube(x, y, z, wallMaterial);
                            break;

                        case 3:   // ★ 怪物区：地板 + 登记坐标（封锁/怪物潮由 MonsterZone 处理）
                            SpawnCube(x, floorBottomY, z, floorMaterial);
                            SpawnCube(x, floorTopY,    z, floorMaterial);
                            monsterCells.Add(new Vector2Int(x, z));
                            break;

                        case 5:   // 商店格（第十周任务 3）：地板 + 上下封盖 + 商店触发区
                            SpawnCube(x, floorBottomY, z, floorMaterial);
                            SpawnCube(x, floorTopY,    z, floorMaterial);

                            // 文档要求：y=0 和 y=6 各加一块普通墙体，中间 y=1..5 放商店区
                            SpawnCube(x, 0, z, wallMaterial);
                            SpawnCube(x, 6, z, wallMaterial);

                            SpawnShopZone(x, z);
                            break;

                        case 8:   // 玩家出生点：地板 + 记下坐标
                            SpawnCube(x, floorBottomY, z, floorMaterial);
                            SpawnCube(x, floorTopY,    z, floorMaterial);

                            playerSpawn = new Vector3(x * cellSize, playerSpawnY, z * cellSize);
                            hasSpawn    = true;
                            break;

                        case 9:   // 下一层（终点）：地板 + 触发区
                            SpawnCube(x, floorBottomY, z, floorMaterial);
                            SpawnCube(x, floorTopY,    z, floorMaterial);

                            SpawnNextStage(x, z);
                            break;

                        // 0 = 什么都不放
                    }
                }
            }

            // ---- 玩家：放到格子 8 的位置 ----
            if (hasSpawn)
            {
                // ★ 记住出生点：开局那一刻 GameUI 还可能再调一次 Teleport
                //   （它有自己的时序），所以这里存下来，
                //   由 GameUI 在地牢模式下改调 TeleportPlayerToSpawn()。
                m_SpawnPosition = playerSpawn;
                m_HasSpawn      = true;

                PlacePlayer(playerSpawn);
            }
            else
            {
                Debug.LogWarning("[地牢] 矩阵里没有格子 8（玩家出生点），玩家不会被移动。");
            }

            // ---- 怪物区：把登记到的格子交给 MonsterZone 管理 ----
            if (MonsterZone.Instance != null)
            {
                MonsterZone.Instance.RegisterCells(monsterCells, cellSize);
            }

            // ---- ★★ 重新烘焙 NavMesh ★★ ----
            //
            //   地图是**运行时才建出来**的，而 NavMeshRuntimeBaker.Ensure()
            //   只烘焙一次。如果它在地图生成之前就被调过（比如场景里有
            //   PuzzleMonster，它的 Start 比这里早），烘焙出来的就是空 NavMesh，
            //   之后所有 Agent 都会报
            //   "Failed to create agent because there is no valid NavMesh"。
            //
            //   所以每次建完图都强制重建一次。
            NavMeshRuntimeBaker.Rebuild();
        }

        /// <summary>在 (x, y, z) 放一个立方体（基础 Cube，不是 WallOccluder）。</summary>
        private void SpawnCube(int x, int y, int z, Material mat)
        {
            var go = GameObject.CreatePrimitive(PrimitiveType.Cube);

            go.name = $"[生成] Cube ({x},{y},{z})";
            go.transform.SetParent(m_Root, false);
            go.transform.position   = new Vector3(x * cellSize, y * cellSize, z * cellSize);
            go.transform.localScale = Vector3.one * cellSize;

            var r = go.GetComponent<Renderer>();
            if (r != null)
            {
                // ★★ 完全透明 ★★
                //
                //   地牢模式靠声波光带感知地形，地板和墙**本来就不该看得见**。
                //   材质留空时用 EchoPuzzle/Invisible —— 那个 shader 直接 discard
                //   所有像素，连深度都不写，所以绝对不会看到任何东西
                //   （比"画成黑色"更彻底：黑色在 Bloom / 后处理下会透出灰）。
                //
                //   注意：Cube 自带 MeshRenderer + BoxCollider，
                //   只是不画而已，碰撞照常生效。
                r.sharedMaterial = mat != null ? mat : InvisibleMaterialOrDefault();
            }
        }

        /// <summary>完全透明材质的共享实例（只建一次）。</summary>
        private static Material s_InvisibleMat;

        /// <summary>取 EchoPuzzle/Invisible 材质。找不到就退化成 URP 的 Unlit 透明材质。</summary>
        private static Material InvisibleMaterialOrDefault()
        {
            if (s_InvisibleMat != null) return s_InvisibleMat;

            // 优先用项目里的资产
            s_InvisibleMat = Resources.Load<Material>("EchoRuntime/EchoInvisible");

#if UNITY_EDITOR
            if (s_InvisibleMat == null)
                s_InvisibleMat = UnityEditor.AssetDatabase.LoadAssetAtPath<Material>(
                    "Assets/EchoPuzzle/Materials/EchoInvisible.mat");
#endif

            // 退路：现场用 shader 建
            if (s_InvisibleMat == null)
            {
                Shader sh = Shader.Find("EchoPuzzle/Invisible");

                if (sh != null)
                {
                    s_InvisibleMat = new Material(sh)
                    {
                        name      = "DungeonInvisibleRuntime",
                        hideFlags = HideFlags.DontSave,
                    };
                }
            }

            if (s_InvisibleMat == null)
            {
                Debug.LogWarning("[地牢] 找不到 EchoPuzzle/Invisible 材质，墙体可能可见。");
            }

            return s_InvisibleMat;
        }

        /// <summary>在格子 (x, z) 放一个 NextStage 触发区。</summary>
        /// <summary>
        /// 生成一个"商店格"（第十周任务 3）。
        ///
        /// 结构和终点格（<see cref="SpawnNextStage"/>）几乎一样：
        ///   · 1×1×6 的 Trigger 盒子（无实体、无碰撞体积）
        ///   · Hide，走和其它生成物同一套启用/删除机制
        ///   · TriggerVolume：把射进来的光带改成蓝色（overrideColor）
        ///   · DungeonShopZone：玩家走进来打开商店界面
        /// </summary>
        private void SpawnShopZone(int x, int z)
        {
            var go = new GameObject($"[生成] Shop ({x},{z})");

            go.transform.SetParent(m_Root, false);
            go.transform.position = new Vector3(x * cellSize, 1f, z * cellSize);

            var box = go.AddComponent<BoxCollider>();
            box.isTrigger = true;
            box.size      = new Vector3(cellSize, 6f, cellSize);
            box.center    = new Vector3(0f, 2f, 0f);

            var hide = go.AddComponent<Hide>();
            hide.hiding = 0;

            var tv = go.AddComponent<TriggerVolume>();
            tv.effect = TriggerEffect.None;      // 只改光带外观，不触发机关

            // ★★ 玩家走进商店时**不要**在脚下炸一大团声波 ★★
            //
            //   需求："玩家进入商店时不会像 trigger volume 那样在脚下炸开大量光带
            //         （应该有个开关的，把那个设为 false 即可）。"
            //
            //   ★ 这个开关就是 TriggerVolume.emitSonarOnTrigger。
            //     设为 false 后，光带**穿过**这一格时仍然会被染色 / 加粗 / 改不透明度
            //     （那是 overrideColor / overrideWidth / overrideAlpha 干的），
            //     只是不会再额外"从玩家脚下放射一次"。
            tv.emitSonarOnTrigger = false;

            tv.overrideColor = true;
            tv.waveColor     = shopWaveColor;

            tv.overrideWidth = true;
            tv.waveWidth     = shopWaveWidth;

            tv.overrideAlpha = true;
            tv.waveAlpha     = shopWaveAlpha;

            go.AddComponent<DungeonShopZone>();

            Debug.Log($"[商店] 本层商店格：格子坐标 ({x}, {z})，" +
                      $"世界坐标 ({x * cellSize:F1}, 1, {z * cellSize:F1})");
        }

        private void SpawnNextStage(int x, int z)
        {
            var go = new GameObject($"[生成] NextStage ({x},{z})");

            go.transform.SetParent(m_Root, false);
            go.transform.position = new Vector3(x * cellSize, 1f, z * cellSize);

            // 触发盒：覆盖 y=0..6 整层
            var box = go.AddComponent<BoxCollider>();
            box.isTrigger = true;
            box.size      = new Vector3(cellSize, 6f, cellSize);
            box.center    = new Vector3(0f, 2f, 0f);

            // Hide：和场景里其它物体一样走同一套"启用/删除"机制
            var hide = go.AddComponent<Hide>();
            hide.hiding = 0;

            var tv = go.AddComponent<TriggerVolume>();

            // 设为 NextStage 类别。
            // ★ 光带外观默认与 Win 相同（nextStageSonar 默认 = DefaultWin），
            //   玩家进入时 EmitTriggerSonar 会释放这套光带 + Destination 音效；
            //   实际"淡出 -> 生成下一层 -> 淡入"由 OnNextStage 事件驱动（见上方）。
            tv.effect = TriggerEffect.NextStage;

            // 光带参数：默认用 Win 那一套，Inspector 上可单独调
            tv.sonar = nextStageSonar;

            // ★★ 射入这个触发区的光带，外观强制改成：★★
            //     粗细 = 0.22 米
            //     不透明度 = 1（保持全亮）
            //     颜色 = 纯白
            //
            //   三个 override 默认分别是 false / true / false，
            //   只开 overrideAlpha 的话宽度和颜色还是原样，所以这里三个都开。
            tv.overrideWidth = true;
            tv.waveWidth     = nextStageWaveWidth;

            tv.overrideAlpha = true;
            tv.waveAlpha     = nextStageWaveAlpha;

            tv.overrideColor = true;
            tv.waveColor     = nextStageWaveColor;

            // ★★ 红色竖线机制已取消 ★★
            //
            //   需求原文："在光带经过怪物变色球和终点区域下方时会产生竖线，
            //             把这个机制给取消掉。"
            //
            //   所以这里不再挂 SenseSphereVisual。
            //   终点触发区对光带的**外观修改**（宽度 / 不透明度 / 颜色）
            //   仍然生效 —— 那走的是 SonarTrailRenderer 的 override 路径，
            //   和竖线是两套东西。

            m_NextStageVolumes.Add(tv);
        }

        /// <summary>把玩家瞬移到出生点（并同步相机）。</summary>
        private void PlacePlayer(Vector3 pos)
        {
            if (m_Player == null) m_Player = FindObjectOfType<PlayerController>();
            if (m_Player == null) return;

            m_Player.Teleport(pos, m_Player.transform.eulerAngles.y, m_Player.Pitch);
        }

        // ------------------------------------------------------------------ 黑幕

        private void OnGUI()
        {
            if (!m_Fading && m_FadeAlpha <= 0.001f) return;

            if (m_Black == null) m_Black = MakeBlack();

            Color prev = GUI.color;
            GUI.color = new Color(0f, 0f, 0f, Mathf.Clamp01(m_FadeAlpha));
            GUI.DrawTexture(new Rect(0f, 0f, Screen.width, Screen.height), m_Black);
            GUI.color = prev;
        }

        private static Texture2D MakeBlack()
        {
            var tex = new Texture2D(1, 1, TextureFormat.RGBA32, false)
            {
                hideFlags = HideFlags.HideAndDontSave
            };

            tex.SetPixel(0, 0, Color.black);
            tex.Apply();
            return tex;
        }


