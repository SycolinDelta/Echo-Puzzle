        //                     出口门（数字 4）系统
        // ──────────────────────────────────────────────────────────────
        //
        //   ★ 4 是**手动填的**，代表"出口门"：
        //     · 位于模板边缘（第一/最后一行、第一/最后一列）的 4 连通块，
        //       就是一个门，按所在边分成 上 / 下 / 左 / 右
        //     · 4 不会出现在四个角上，一条边上只有一个门
        //
        //   ★ 门的取值规则：
        //     · 对侧是**空块** -> 一律 2（墙），不可通行
        //     · 对侧是**非空块** -> **可以**是 1（地板），也可以是 2
        //         - Y（出生） / Z（终点）：从所有"可以对 1"的门里
        //                                   **随机挑 1 个** 设为 1，其余全设 2
        //         - A（怪物）           ：随机挑 **至少 1 个** 设为 1
        //     · 相邻两块的门**必须同状态**（a11 右侧门=1 -> a12 左侧门也=1）
        //     · 最终必须能从 Y 走到 Z（否则重新生成布局 / 重新分配门）

        /// <summary>方向常量：上 / 下 / 左 / 右。</summary>
        private static readonly Vector2Int[] DirVec =
        {
            new Vector2Int(-1, 0),   // 0 = 上
            new Vector2Int( 1, 0),   // 1 = 下
            new Vector2Int( 0,-1),   // 2 = 左
            new Vector2Int( 0, 1),   // 3 = 右
        };

        /// <summary>相反方向：上<->下，左<->右。</summary>
        private static int Opposite(int dir) => dir < 2 ? 1 - dir : 5 - dir;

        /// <summary>方向名（调试用）。</summary>
        private static string DirName(int d)
        {
            switch (d)
            {
                case 0: return "上";
                case 1: return "下";
                case 2: return "左";
                default: return "右";
            }
        }

        private static string[] DirNamesAt(List<int> dirs)
        {
            var arr = new string[dirs.Count];
            for (int i = 0; i < dirs.Count; i++) arr[i] = DirName(dirs[i]);
            return arr;
        }

