        //              ★★ 字母 → 模板池 注册表 ★★
        // ══════════════════════════════════════════════════════════════
        //
        //   核心思想：**一个字母可以对应多个模板矩阵**。
        //
        //   每个 A 块在生成时，都会从 A 的模板池里**独立随机**抽一个；
        //   同一张地图里两个 A 可以抽到相同或不同的模板。
        //
        //   ── 标记名和绑定关系无关 ──────────────────────────────────
        //     决定"某个模板属于哪个字母"的**只有**下面这张注册表。
        //     变量叫 TemplateBB 也行，只要在注册表里挂到 "A" 下面，
        //     它就会被当成 A 的模板用。
        //
        //   ── 扩充新字母怎么做 ──────────────────────────────────────
        //     1) 新写一个 public static readonly int[,] TemplateXX = ...
        //     2) 在下方 CreateTemplatePools() 里加一行：
        //            { "L",  new[] { TemplateL1, TemplateL2 } },
        //     3) 在 BuildSlots / RandomLayout 里把 "L" 放进布局即可。
        //
        //   ── 字母含义（当前） ──────────────────────────────────────
        //     Y = 出生房  -> TemplateYA                （模板里有数字 8）
        //     A = 怪物房  -> TemplateAA / AB / AC      （模板里有数字 3）
        //     Z = 终点房  -> TemplateZA                （模板里有数字 9）
        //
        //   ★ 命名规则：
        //       Y / A / Z         是**字母**（未知量），填在分块矩阵里
        //       YA / AA / ZA ...  是**具体模板**，挂在某一组下面
        //     A 可以等于 AA、AB、AC，但**不能说 A 等于 A**。
        /// <summary>
        /// 字母 → 模板矩阵数组（模板池）。
        ///
        /// ★ key   = 分块矩阵里用的字母（"Y" / "A" / "Z" / 将来新增的...）
