        /// <summary>
        /// 取分块矩阵里某一格的模板（先确保布局已建立）。
        /// </summary>
        private static int[,] SlotAt(int r, int c)
        {
            BuildSlots();

            if (r < 0 || r >= GridRows || c < 0 || c >= GridCols) return null;

            return s_Slots[r, c];
        }

        /// <summary>
        /// 拼好的大矩阵（140 行 × 140 列），生成逻辑统一读它。
        /// </summary>
        public static int[,] MapMatrix
        {
            get
            {
                if (s_MapCache != null) return s_MapCache;

                var big = new int[RowsX, ColsZ];

                for (int r = 0; r < GridRows; r++)
                {
                    for (int c = 0; c < GridCols; c++)
                    {
                        int[,] mod = SlotAt(r, c);
                        if (mod == null) continue;

                        int ox = r * ModuleSize;
                        int oz = c * ModuleSize;

                        for (int x = 0; x < ModuleSize; x++)
                        {
                            for (int z = 0; z < ModuleSize; z++)
                                big[ox + x, oz + z] = mod[x, z];
                        }
                    }
                }

                s_MapCache = big;
                return s_MapCache;
            }
        }

        private static int[,] s_MapCache;

        /// <summary>
        /// 按大矩阵坐标 (x, z) 取格子值 —— **不经过拼装**，直接算落在哪一块里。
        ///
        /// ★ 生成循环用这个更快（省掉一次 140×140 的复制）。
        /// ★ 越界 / 空格子返回 0（等同"什么都不放"）。
        /// </summary>
        public static int GetCell(int x, int z)
        {
            if (x < 0 || x >= RowsX) return 0;
            if (z < 0 || z >= ColsZ) return 0;

            int br = x / ModuleSize;      // 块行 0..3
            int bc = z / ModuleSize;      // 块列 0..3

            int lx = x % ModuleSize;      // 模块内 X
            int lz = z % ModuleSize;      // 模块内 Z

            int[,] mod = SlotAt(br, bc);
            if (mod == null) return 0;

            return mod[lx, lz];
        }

