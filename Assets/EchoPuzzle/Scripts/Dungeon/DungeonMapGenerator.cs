        /// <summary>
        /// 取某个字母的**全部**模板（不要改返回值里的数组内容）。
        /// 字母不存在返回 null。
        /// </summary>
        public static int[][,] GetTemplatePool(string letter)
        {
            if (string.IsNullOrEmpty(letter)) return null;

            int[][,] pool;
            return s_TemplatePools.TryGetValue(letter, out pool) ? pool : null;
        }

        /// <summary>
        /// 从某个字母的模板池里**随机**抽一个模板。
        ///
        /// ★ 这是给"每块独立随机抽模板"用的主入口。
        ///   字母没有注册 / 池子是空的 -> 返回 null。
        /// </summary>
        public static int[,] GetTemplate(string letter, System.Random rng)
        {
            // ★ 调试：让出生房必定出带商店的那套模板（测商店用）
            if (DebugForceShopRoom && letter == "Y") return TemplateYB;

            int[][,] pool = GetTemplatePool(letter);
            if (pool == null || pool.Length == 0) return null;

            // 没有 rng 就退化成取第一个（保证不会因为空引用崩掉）
            if (rng == null) return pool[0];

            return pool[rng.Next(pool.Length)];
        }

        /// <summary>
        /// 取某个字母的一个模板（不带随机 —— 取池子里第一个）。
        ///
        /// ★ 保留这个重载是为了兼容"只想看一眼默认模板"的调用方
        ///   （比如 SetSlot 的调试入口、编辑器打印矩阵）。
        /// </summary>
        public static int[,] GetTemplate(string letter)
        {
            int[][,] pool = GetTemplatePool(letter);
            return (pool != null && pool.Length > 0) ? pool[0] : null;
        }

        /// <summary>
        /// 按名字往分块矩阵里放**一个随机模板**。
        ///
        /// r = 块行（0..3，从上到下），c = 块列（0..3，从左到右）。
        /// name 传 null / 空串 = 把这一格清空。
        ///
        /// ★ 该字母有多套模板时，这里会随机抽一套。
        /// </summary>
        public static void SetSlot(int r, int c, string name, System.Random rng = null)
        {
            if (r < 0 || r >= GridRows || c < 0 || c >= GridCols) return;

            s_Slots[r, c] = string.IsNullOrEmpty(name) ? null : GetTemplate(name, rng);

            // 布局改了 -> 拼装缓存要作废
            s_MapCache = null;
        }

