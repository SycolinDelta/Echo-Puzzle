        }

        /// <summary>
        /// 模板矩阵的内容签名 → 门信息。
        ///
        /// ★ 用**内容签名**做 key（而不是矩阵引用）：
        ///   同一个字母下可以有多套模板（AA / AB / AC），
        ///   每套的门位置可能不同，必须逐块算；
        ///   而 BuildSlots 每次传进来的是**新副本**，
        ///   按引用做 key 会永远 miss、缓存无限膨胀。
        /// </summary>
        private static readonly Dictionary<string, GateInfo> s_GateCache =
            new Dictionary<string, GateInfo>();

        /// <summary>
        /// 找出**某个具体模板矩阵**四条边上的出口门。
        ///
        /// ★ 改成按矩阵算了：
        ///   同一个字母（比如 A）现在可能有多套模板（AA / AB / AC），
        ///   每套的门位置可以不一样，所以必须针对"实际用哪套"来算。
        /// </summary>
        private static GateInfo GetGates(int[,] mat)
        {
            if (mat == null) return new GateInfo();

            string key = GateSignature(mat);

            GateInfo gi;
            if (s_GateCache.TryGetValue(key, out gi) && gi != null) return gi;

            gi = new GateInfo();

            // 收集所有 4 的坐标
            var all4 = new HashSet<Vector2Int>();
            for (int x = 0; x < ModuleSize; x++)
                for (int z = 0; z < ModuleSize; z++)
                    if (mat[x, z] == 4) all4.Add(new Vector2Int(x, z));

            // 4-邻接连通块
            var visited = new HashSet<Vector2Int>();

            foreach (Vector2Int seed in all4)
            {
                if (visited.Contains(seed)) continue;

                var comp = new List<Vector2Int>();
                var q = new Queue<Vector2Int>();
                q.Enqueue(seed); visited.Add(seed);

                while (q.Count > 0)
                {
                    Vector2Int p = q.Dequeue();
                    comp.Add(p);

                    for (int d = 0; d < 4; d++)
                    {
                        var n = new Vector2Int(p.x + DirVec[d].x, p.y + DirVec[d].y);
                        if (all4.Contains(n) && !visited.Contains(n))
                        {
                            visited.Add(n);
                            q.Enqueue(n);
                        }
                    }
                }

                // 这一块接触哪条边（只看第一条命中的边，一个块最多算一条边）
                int side = -1;

                for (int i = 0; i < comp.Count && side < 0; i++)
                {
                    Vector2Int p = comp[i];
                    if (p.x == 0)                    side = 0;   // 上
                    else if (p.x == ModuleSize - 1)  side = 1;   // 下
                    else if (p.y == 0)               side = 2;   // 左
                    else if (p.y == ModuleSize - 1)  side = 3;   // 右
                }

                if (side < 0) continue;

                List<Vector2Int> list;
                if (!gi.Gates.TryGetValue(side, out list))
                {
                    list = new List<Vector2Int>(comp.Count);
                    gi.Gates[side] = list;
                }
                list.AddRange(comp);
            }

            s_GateCache[key] = gi;
            return gi;
        }

        /// <summary>
        /// 算一份"门位置签名"：只需把 4 的位置编码进去就够了 ——
        /// 门只由 4 的位置决定，其它格子无关。
        ///
        /// ★ 这样 AA / AB / AC 只要 4 的位置相同就复用同一份门信息，
        ///   4 的位置不同就各算各的。
        /// </summary>
        private static string GateSignature(int[,] mat)
        {
            var sb = new System.Text.StringBuilder(ModuleSize * ModuleSize / 8 + 32);

            for (int x = 0; x < ModuleSize; x++)
            {
                for (int z = 0; z < ModuleSize; z++)
                {
                    sb.Append(mat[x, z] == 4 ? '1' : '0');
                }
            }

            return sb.ToString();
        }

